using System;
using System.Collections.Generic;
using System.Collections.ObjectModel;

namespace Paramatrix.Content
{
    /// <summary>Architecture 0.3.1 §4.3. <c>reconstructible</c> is not part of MVP (decision A9).</summary>
    public enum Persistence
    {
        Persistent = 1,
        Transient,
    }

    /// <summary>Architecture 0.3.1 §4.4.</summary>
    public enum MutationPolicy
    {
        ScenarioOnly = 1,
        SystemOnly,
        ScenarioOrSystem,
    }

    /// <summary>Result of checking a value against a State definition.</summary>
    public enum ValueCheck
    {
        Ok = 1,
        TypeMismatch,
        OutOfRange,
        InvalidEnumValue,
    }

    /// <summary>Immutable declaration of one State property (Architecture 0.3.1 §4).</summary>
    public sealed class StateDefinition
    {
        private readonly HashSet<string> _enumLookup;

        public StateDefinition(
            StateAddress address,
            StateType type,
            StateValue defaultValue,
            Persistence persistence,
            MutationPolicy mutationPolicy,
            int? min,
            int? max,
            IEnumerable<string> enumValues,
            bool isBuiltIn,
            SourceLocation source)
        {
            if (!address.IsValid)
            {
                throw new ArgumentException("Address is not initialized.", nameof(address));
            }

            Address = address;
            Type = type;
            Persistence = persistence;
            MutationPolicy = mutationPolicy;
            Min = min;
            Max = max;
            IsBuiltIn = isBuiltIn;
            Source = source;

            var values = new List<string>(enumValues ?? Array.Empty<string>());
            if (type == StateType.Enum && values.Count == 0)
            {
                throw new ArgumentException("Enum definition needs values.", nameof(enumValues));
            }

            if (type != StateType.Enum && values.Count > 0)
            {
                throw new ArgumentException("Only enum definitions have values.", nameof(enumValues));
            }

            if (type != StateType.Integer && (min.HasValue || max.HasValue))
            {
                throw new ArgumentException("Only integer definitions have min/max.");
            }

            EnumValues = new ReadOnlyCollection<string>(values);
            _enumLookup = new HashSet<string>(values, StringComparer.Ordinal);

            if (Check(defaultValue) != ValueCheck.Ok)
            {
                throw new ArgumentException($"Default {defaultValue} is not valid for {address}.", nameof(defaultValue));
            }

            Default = defaultValue;
        }

        public StateAddress Address { get; }

        public StateType Type { get; }

        public StateValue Default { get; }

        public Persistence Persistence { get; }

        public MutationPolicy MutationPolicy { get; }

        public int? Min { get; }

        public int? Max { get; }

        /// <summary>Allowed enum values in declaration order; empty for non-enum types.</summary>
        public IReadOnlyList<string> EnumValues { get; }

        /// <summary>Generated by the loader (character <c>location</c>, item <c>holder</c>), not declared in <c>states</c>.</summary>
        public bool IsBuiltIn { get; }

        public SourceLocation Source { get; }

        /// <summary>Checks type, integer range and enum membership. The only place these rules live.</summary>
        public ValueCheck Check(StateValue value)
        {
            if (value.Type != Type)
            {
                return ValueCheck.TypeMismatch;
            }

            switch (Type)
            {
                case StateType.Integer:
                    var number = value.AsInteger;
                    return (Min.HasValue && number < Min.Value) || (Max.HasValue && number > Max.Value)
                        ? ValueCheck.OutOfRange
                        : ValueCheck.Ok;
                case StateType.Enum:
                    return _enumLookup.Contains(value.AsEnum) ? ValueCheck.Ok : ValueCheck.InvalidEnumValue;
                default:
                    return ValueCheck.Ok;
            }
        }

        public bool Allows(MutationPolicy required) =>
            MutationPolicy == MutationPolicy.ScenarioOrSystem || MutationPolicy == required;

        public override string ToString() => $"{Address}: {StateValue.TypeName(Type)}";
    }
}
